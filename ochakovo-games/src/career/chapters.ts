import { lazy, type ComponentType, type LazyExoticComponent } from 'react'

// Главы игры: одна глава — одна профессия. Тексты черновые, согласовать с заказчиком
// (docs/PLAN.md, п. 9). Последний уровень главы — экзамен: после него открывается следующая.

export interface LevelInfo {
  title: string
  /** Что нужно сделать — показывается перед стартом */
  goal: string
  /** Уровень ещё не сделан: в списке виден, но закрыт даже при ?unlock */
  soon?: boolean
}

/** То, что получает компонент уровней главы от общей оболочки */
export interface LevelProps {
  chapter: ChapterInfo
  levelIndex: number
  /** Пауза оболочки (кнопка, «назад», игра свёрнута) — уровень должен остановиться */
  paused: boolean
  /** Уровень закончен: 0 — не пройден, 1–3 — звёзды */
  onFinish: (stars: number) => void
  /** Поставить на паузу — для глав на весь экран, у которых своя кнопка паузы */
  onPause: () => void
}

export interface ChapterInfo {
  id: string
  /** Профессия */
  title: string
  tagline: string
  /** Акцентный цвет главы */
  color: string
  icon: ChapterIconName
  /** Основная механика — пока показывается в заглушке уровня */
  mechanic: string
  mentor: { name: string; role: string }
  /** Экраны вступления от наставника */
  intro: string[]
  /** Карточка «Чем занимается…» после экзамена */
  facts: string[]
  levels: LevelInfo[]
  /** Уровни главы (Phaser). Пока не указано — играется заглушка */
  component?: LazyExoticComponent<ComponentType<LevelProps>>
  /** Уровень на весь экран: без шапки и фона оболочки, кнопку паузы рисует сама глава */
  fullscreen?: boolean
}


import { Grid, type Palette } from '../pixel'

// Пиксельный портрет мастера цеха: мужчина средних лет, деловой и собранный.
// Белая каска с красной полосой, красная спецовка со светоотражающими полосами, планшет с бумагами.
// Собирается на сетке Grid, как портрет мастера пресса; рисуется в ForemanArt.tsx.

export const FOREMAN_W = 36
export const FOREMAN_H = 52

export const FOREMAN_PAL = {
  k: '#1b1f2e', // контур
  h: '#e0a98a', // кожа
  H: '#b97b5e', // кожа в тени, морщины
  q: '#d4806c', // румянец, кончик носа
  b: '#3a2a22', // тёмные волосы, брови, щетина
  w: '#8d949b', // седина на висках
  e: '#f4ece0', // белок глаза
  M: '#6e302c', // рот
  v: '#f0f2f4', // каска, белый
  V: '#c4c8cc', // каска в тени
  r: '#cd004b', // фирменный красный
  R: '#8f0035', // красный в тени
  p: '#e8366f', // красный на свету
  y: '#f4ece0', // светоотражающая полоса, воротник
  Y: '#c9bfae', // белое в тени
  t: '#5b6770', // футболка под спецовкой
  o: '#8b5a2b', // дерево планшета
  s: '#7f909c', // сталь зажима
  S: '#b7c5cf', // сталь на свету
  g: '#2d2a28', // грязь, масло
} satisfies Palette

/** Детерминированный «случайный» ряд: портрет не должен меняться между запусками */
const hash = (a: number, b: number) => {
  const n = Math.sin(a * 127.1 + b * 311.7) * 43758.5453
  return n - Math.floor(n)
}

export function foremanRows(): string[] {
  const g = new Grid(FOREMAN_W, FOREMAN_H)
  const ellipse = (cx: number, cy: number, rx: number, ry: number, c: string, keep?: (x: number, y: number) => boolean) => {
    for (let y = 0; y < g.h; y++)
      for (let x = 0; x < g.w; x++) {
        const dx = (x + 0.5 - cx) / rx
        const dy = (y + 0.5 - cy) / ry
        if (dx * dx + dy * dy <= 1 && (!keep || keep(x, y))) g.set(x, y, c)
      }
  }

  // Спецовка: плечи расширяются к груди
  const half = (y: number) => [8, 10, 12, 13, 14][y - 33] ?? 15
  for (let y = 33; y < g.h; y++) g.rect(18 - half(y), y, half(y) * 2, 1, 'r')
  // свет слева, тень справа
  for (let y = 34; y < g.h; y++) {
    g.set(18 - half(y) + 1, y, 'p')
    g.rect(18 + half(y) - 4, y, 3, 1, 'R')
  }
  g.rect(10, 33, 8, 1, 'p')
  // футболка в вырезе и белый отложной воротник
  const v = [4, 4, 3, 3, 2, 2, 1]
  v.forEach((h, i) => g.rect(18 - h, 34 + i, h * 2, 1, 't'))
  g.rect(12, 33, 3, 5, 'y')
  g.rect(21, 33, 3, 5, 'y')
  g.rect(12, 37, 3, 1, 'Y')
  g.rect(21, 37, 3, 1, 'Y')
  // застёжка
  for (let y = 41; y < g.h; y++) g.set(18, y, y % 2 ? 'R' : 'r')
  // светоотражающие полосы на груди и плечах
  g.rect(4, 45, 28, 1, 'y')
  g.rect(4, 46, 28, 1, 'Y')
  g.rect(4, 49, 28, 1, 'y')
  g.rect(4, 50, 28, 1, 'Y')
  g.rect(4, 35, 2, 1, 'y')
  g.rect(30, 35, 2, 1, 'y')
  // нагрудный карман слева с ручкой
  g.rect(7, 40, 7, 4, 'R')
  g.rect(8, 41, 5, 2, 'r')
  g.set(12, 39, 'S')
  g.set(12, 40, 'k')
  // бейдж с красным знаком справа
  g.stamp(['yyyyyyy', 'yryyryy', 'yrrrrry', 'yyyyyyy'], 22, 40)

  // Планшет с бумагами в руке: зажим сверху, лист, пальцы поверх нижнего края
  g.rect(25, 37, 9, 12, 'o')
  g.rect(26, 39, 7, 9, 'y')
  g.rect(28, 36, 3, 2, 's')
  g.set(28, 36, 'S')
  for (const y of [41, 43, 45]) g.rect(27, y, 5, 1, 'Y')
  g.rect(24, 46, 4, 4, 'h')
  g.rect(24, 49, 4, 1, 'H')
  g.rect(27, 47, 1, 1, 'H')

  // Шея и голова: лицо шире и жёстче, чем у старого мастера
  g.rect(14, 29, 8, 5, 'h')
  g.rect(14, 29, 8, 2, 'H')
  ellipse(18, 19.5, 8, 10.5, 'h')
  // уши и аккуратные виски с проседью
  g.rect(9, 17, 2, 5, 'h')
  g.rect(25, 17, 2, 5, 'h')
  g.rect(9, 18, 1, 3, 'H')
  g.rect(26, 18, 1, 3, 'H')
  g.rect(9, 13, 2, 4, 'b')
  g.rect(25, 13, 2, 4, 'b')
  g.set(9, 15, 'w')
  g.set(26, 15, 'w')
  g.set(10, 16, 'w')
  g.set(25, 16, 'w')

  // Каска: белый купол с красной полосой по гребню, козырёк, фирменный знак
  ellipse(18, 11.5, 10, 7.5, 'v', (_, y) => y <= 11)
  for (const [x, y] of [[12, 7], [13, 6], [14, 5], [11, 8], [12, 8], [15, 5]]) g.set(x, y, 'y')
  g.rect(8, 12, 20, 1, 'v')
  g.rect(6, 12, 2, 1, 'V')
  g.rect(28, 12, 2, 1, 'V')
  g.rect(9, 13, 18, 1, 'V')
  g.rect(11, 14, 14, 1, 'H')
  // красная полоса по гребню и по ободу
  g.rect(16, 3, 4, 9, 'r')
  g.rect(16, 3, 1, 9, 'p')
  g.rect(19, 3, 1, 9, 'R')
  g.rect(8, 11, 20, 1, 'r')
  g.rect(8, 11, 20, 1, 'r')
  g.rect(24, 11, 4, 1, 'R')

  // Лицо: приподнятые брови, открытые глаза, нос, сдержанная полуулыбка
  g.rect(12, 15, 4, 1, 'b')
  g.rect(20, 15, 4, 1, 'b')
  g.set(11, 16, 'b')
  g.set(24, 16, 'b')
  g.rect(13, 17, 3, 1, 'e')
  g.rect(20, 17, 3, 1, 'e')
  g.rect(14, 17, 1, 2, 'k')
  g.rect(21, 17, 1, 2, 'k')
  g.rect(13, 19, 3, 1, 'H')
  g.rect(20, 19, 3, 1, 'H')
  g.rect(17, 18, 1, 3, 'H')
  g.rect(17, 21, 2, 1, 'q')
  g.set(18, 20, 'h')
  g.rect(12, 20, 2, 1, 'q')
  g.rect(22, 20, 2, 1, 'q')
  // носогубные складки
  g.set(14, 22, 'H')
  g.set(22, 22, 'H')
  // рот: сдержанный, чуть приподнят только правый уголок
  g.rect(15, 24, 5, 1, 'M')
  g.set(20, 23, 'M')
  g.set(21, 23, 'H')
  g.set(15, 25, 'H')

  // лёгкая небритость на подбородке
  for (let y = 25; y < 30; y++)
    for (let x = 13; x < 23; x++) if (g.get(x, y) === 'h' && hash(x, y) > 0.8) g.set(x, y, 'H')

  g.outline('k')

  // Грязь и масло на спецовке — после контура, чтобы не обводились
  for (let i = 0; i < 6; i++) {
    const x = 5 + Math.floor(hash(i, 31) * 26)
    const y = 36 + Math.floor(hash(i, 32) * 15)
    if (g.get(x, y) === 'r' || g.get(x, y) === 'R') g.set(x, y, 'g')
  }
  return g.rows()
}

import { Grid, type Palette } from '../bottling/pixel'

// Пиксельный портрет лаборанта по REF/лаба.txt: женщина около 40 лет, белая медицинская шапочка
// с убранными волосами, очки в толстой тёмной оправе с бликом, белоснежный халат с эмблемой «О»,
// бейдж на шее и планшет экраном к себе. Собирается на сетке Grid, рисуется в LabArt.tsx.

export const LAB_W = 36
export const LAB_H = 52

export const LAB_PAL = {
  k: '#1b1f2e', // контур
  h: '#f0c4a8', // кожа
  H: '#cf9a7e', // кожа в тени, морщинки
  q: '#e39a8c', // румянец
  b: '#4a3326', // брови, выбившиеся пряди
  e: '#f4ece0', // белок глаза
  M: '#c2475f', // помада
  v: '#fafbfc', // белый халат, шапочка
  V: '#d3d9de', // белое в тени
  Y: '#aab3bb', // складки, глубокая тень
  u: '#5fa3b5', // хирургическая форма в вырезе
  G: '#23252b', // оправа очков
  l: '#cfe7ee', // стекло
  L: '#ffffff', // блик на стекле
  r: '#cd004b', // фирменный красный: эмблема, шнурок
  R: '#8f0035', // красный в тени
  s: '#7f909c', // сталь
  S: '#b7c5cf', // сталь на свету
  t: '#4b545c', // задняя крышка планшета
  T: '#2a3036', // кант планшета
} satisfies Palette

export function labRows(): string[] {
  const g = new Grid(LAB_W, LAB_H)
  const ellipse = (cx: number, cy: number, rx: number, ry: number, c: string, keep?: (x: number, y: number) => boolean) => {
    for (let y = 0; y < g.h; y++)
      for (let x = 0; x < g.w; x++) {
        const dx = (x + 0.5 - cx) / rx
        const dy = (y + 0.5 - cy) / ry
        if (dx * dx + dy * dy <= 1 && (!keep || keep(x, y))) g.set(x, y, c)
      }
  }

  // Халат: плечи расширяются к груди, тень справа
  const half = (y: number) => [7, 9, 10, 12, 13][y - 33] ?? 14
  for (let y = 33; y < g.h; y++) {
    g.rect(18 - half(y), y, half(y) * 2, 1, 'v')
    g.rect(18 + half(y) - 4, y, 3, 1, 'V')
  }
  // форма в вырезе и лацканы
  const cut = [4, 4, 3, 3, 2, 2, 1]
  cut.forEach((h, i) => g.rect(18 - h, 34 + i, h * 2, 1, 'u'))
  for (let i = 0; i < 7; i++) {
    g.set(13 + Math.round(i * 0.5), 34 + i, 'V')
    g.set(23 - Math.round(i * 0.5), 34 + i, 'V')
  }
  // застёжка и нагрудный карман
  for (let y = 41; y < g.h; y++) g.set(18, y, y % 4 === 0 ? 'Y' : 'V')
  g.rect(24, 44, 6, 1, 'V')
  // эмблема «О» на груди слева (слева от зрителя)
  g.stamp(['.rrrr.', 'rr..rr', 'rr..rr', 'rr..rr', 'rr..rr', '.rrrr.'], 7, 39)
  g.rect(7, 42, 1, 3, 'R')
  // бейдж на шнурке
  for (let i = 0; i < 9; i++) {
    g.set(13 + Math.round(i * 0.45), 34 + i, 'r')
    g.set(23 - Math.round(i * 0.45), 34 + i, 'r')
  }
  g.stamp(['SSSSS', 'S...S', 'SYhYS', 'S...S', 'SSSSS'], 16, 43)
  g.set(18, 43, 'r')

  // Планшет в руках: видна задняя крышка, экран смотрит на лаборанта
  g.rect(22, 41, 10, 10, 'T')
  g.rect(23, 42, 8, 8, 't')
  g.set(24, 43, 'S')
  g.rect(26, 45, 2, 2, 's')
  g.rect(19, 46, 4, 4, 'h')
  g.rect(19, 49, 4, 1, 'H')
  g.rect(21, 44, 2, 2, 'h')

  // Шея и голова
  g.rect(15, 29, 6, 5, 'h')
  g.rect(15, 29, 6, 2, 'H')
  // лицо мягче: широкий лоб и округлые скулы сужаются к небольшому подбородку
  ellipse(18, 16.5, 8, 8, 'h')
  ellipse(18, 21.5, 6.5, 8.5, 'h')
  g.rect(9, 17, 2, 4, 'h')
  g.rect(25, 17, 2, 4, 'h')
  // серёжки
  g.set(9, 21, 'S')
  g.set(26, 21, 'S')
  g.set(9, 22, 'r')
  g.set(26, 22, 'r')

  // Шапочка: белый купол с лёгкими складками, волосы убраны, на висках выбились пряди
  ellipse(18, 11.5, 10, 7.5, 'v', (_, y) => y <= 11)
  g.rect(8, 12, 20, 1, 'V')
  g.rect(9, 13, 18, 1, 'V')
  g.rect(24, 5, 3, 7, 'V')
  for (let y = 4; y < 11; y++) g.set(18 + Math.round((y - 4) * 0.2), y, 'V')
  g.set(12, 6, 'V')
  g.set(13, 5, 'V')
  // тёмные локоны вдоль лица
  g.rect(10, 13, 1, 7, 'b')
  g.rect(25, 13, 1, 7, 'b')
  g.set(11, 14, 'b')
  g.set(24, 14, 'b')

  // Брови, очки в толстой тёмной оправе с бликом
  g.rect(12, 14, 4, 1, 'b')
  g.set(16, 13, 'b')
  g.rect(20, 14, 4, 1, 'b')
  g.set(19, 13, 'b')
  g.rect(11, 16, 6, 5, 'G')
  g.rect(19, 16, 6, 5, 'G')
  g.rect(12, 17, 4, 3, 'l')
  g.rect(20, 17, 4, 3, 'l')
  g.rect(17, 17, 2, 1, 'G')
  g.set(10, 17, 'G')
  g.set(25, 17, 'G')
  // глаза за стеклом и блик
  g.rect(13, 18, 2, 1, 'e')
  g.rect(21, 18, 2, 1, 'e')
  g.set(14, 18, 'k')
  g.set(22, 18, 'k')
  g.set(12, 17, 'L')
  g.set(13, 17, 'L')
  // нос, румянец, складки возраста
  g.rect(17, 21, 2, 1, 'H')
  g.set(17, 22, 'q')
  g.rect(12, 22, 3, 1, 'q')
  g.rect(21, 22, 3, 1, 'q')
  // доброжелательная лёгкая улыбка
  g.rect(16, 24, 4, 1, 'M')
  g.rect(15, 25, 6, 1, 'M')
  g.rect(16, 26, 4, 1, 'q')
  g.set(14, 24, 'H')
  g.set(21, 24, 'H')

  g.outline('k')
  return g.rows()
}
